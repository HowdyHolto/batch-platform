interface DotMatrixProps {
  pattern: number[][];
  color: string;
  dotRadius?: number;
  gap?: number;
  className?: string;
}

export function DotMatrix({ pattern, color, dotRadius = 2.5, gap = 8, className = '' }: DotMatrixProps) {
  const cols = pattern[0]?.length ?? 0;
  const rows = pattern.length;
  const w = cols * gap;
  const h = rows * gap;

  return (
    <svg viewBox={`0 0 ${w} ${h}`} className={className} aria-hidden>
      {pattern.map((row, y) =>
        row.map((cell, x) =>
          cell > 0 ? (
            <circle
              key={`${x}-${y}`}
              cx={x * gap + gap / 2}
              cy={y * gap + gap / 2}
              r={dotRadius * (cell === 2 ? 1.4 : 1)}
              fill={color}
            />
          ) : null
        )
      )}
    </svg>
  );
}

